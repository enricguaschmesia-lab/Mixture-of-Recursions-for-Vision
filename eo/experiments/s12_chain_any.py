def _seq_class():
    import torch
    from eo.data.eo_vocab import IMAGE_MODALITIES, MODALITY_TO_ID, PAD_ID, get_modality

    class ChainSeq(torch.utils.data.Dataset):
        """[S?, X?, T], assembled exactly as TargetLast assembles a row. `x` is None (no X),
        "row" (true), "donor" (another row's), or "gen" (the generated bodies in `gen`)."""

        def __init__(self, base, rows, S, X, T, with_s=True, x=None, donor=None, gen=None):
            self.base, self.rows, self.S, self.X, self.T = base, list(rows), S, X, T
            self.with_s, self.x, self.donor, self.gen = with_s, x, donor, gen

        def __len__(self):
            return len(self.rows)

        def _x_chunk(self, row):
            if self.x == "row":
                return self.base._load_chunk(self.X, row)
            if self.x == "donor":
                return self.base._load_chunk(self.X, self.donor[row])
            info = get_modality(self.X)
            return torch.cat([torch.tensor([info.bo_id]), torch.as_tensor(self.gen[row]).long(),
                              torch.tensor([info.eo_id])])

        def __getitem__(self, i):
            from lm_dataset.sequence_assembly import assemble_sequence
            row = self.rows[i]
            mods = ([self.S] if self.with_s else []) + ([self.X] if self.x else []) + [self.T]
            chunks = ([self.base._load_chunk(self.S, row)] if self.with_s else []) \
                + ([self._x_chunk(row)] if self.x else []) + [self.base._load_chunk(self.T, row)]
            return assemble_sequence(
                chunks=chunks, chunk_modality_ids=[MODALITY_TO_ID[m] for m in mods],
                chunk_shufflable=[m in IMAGE_MODALITIES for m in mods],
                max_length=self.base.max_length, pad_id=PAD_ID,
                rng=np.random.default_rng(0), shuffle_image_patches=False)

    return ChainSeq


def _same(a, b):
    import torch
    return set(a) == set(b) and all(torch.equal(a[k], b[k]) for k in a)


def _derangement(rows, key, seed):
    rng = np.random.default_rng([seed, zlib.crc32(key.encode())])
    p = [rows[i] for i in rng.permutation(len(rows))]
    return {p[i]: p[(i + 1) % len(p)] for i in range(len(p))}


def _prompt(seq, T):
    """The generation prompt for a scored sequence: its ids through <BO_T>."""
    from eo.data.eo_vocab import get_modality
    ids = seq["input_ids"]
    bo = get_modality(T).bo_id
    k = int((ids == bo).nonzero()[0, 0])
    return ids[:k + 1].clone()


def run(args) -> int:
    import torch
    from eo.data.eo_vocab import MODALITIES, PAD_ID, get_modality
    from eo.data.eval_split import load_eval_rows
    from eo.eval import teacher_forced as TF
    from eo.generate import conditional as G
    sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
    import prepare_decode as PD

    S, X, T = args.source, args.mid, args.target
    if len({S, X, T}) != 3:
        raise SystemExit("source, mid and target must differ")
    if torch.cuda.device_count() != 1:
        raise SystemExit("pin exactly one GPU")
    gpu = torch.cuda.get_device_name(0)
    if args.expect_gpu not in gpu:
        raise SystemExit(f"CUDA sees {gpu!r}, expected {args.expect_gpu!r}")
    torch.manual_seed(42)
    model, cfg = G.build_model(args.arm_config, str(Path(args.run_dir) / args.checkpoint))
    ds, _ = TF.eval_loader(cfg, num_workers=args.num_workers)
    out = out_dir(args) / args.arm_tag
    out.mkdir(parents=True, exist_ok=True)
    ChainSeq = _seq_class()
    t0 = time.perf_counter()
    XB = get_modality(X).tokens_per_sample

    # rows: every held-out row carrying S, X and T, or a seeded sample of them
    cand = [int(r) for r in load_eval_rows(root_dir=ROOT)
            if all(m in ds.present_modalities(int(r)) for m in (S, X, T))]
    if args.rows and args.rows < len(cand):
        rng = np.random.default_rng([args.seed, zlib.crc32(f"{S}|{X}|{T}".encode())])
        rows = sorted(int(r) for r in rng.choice(cand, size=args.rows, replace=False))
    else:
        rows = sorted(cand)
    donor = _derangement(rows, f"control|{S}|{X}|{T}", args.seed)
    true_x = {r: ds._load_chunk(X, r)[1:-1] for r in rows}
    donor_x = {r: ds._load_chunk(X, donor[r])[1:-1] for r in rows}

    # ---- exact controls, before any GPU work
    n = len(rows)
    rng_order = list(MODALITIES)
    direct, orc = ChainSeq(ds, rows, S, X, T), ChainSeq(ds, rows, S, X, T, x="row")
    tl = {k: TF.TargetLast(ds, rows, T, sources=v) for k, v in
          (("S", [S]), ("X", [X]), ("none", []), ("SX", [S, X]))}
    ch_true = ChainSeq(ds, rows, S, X, T, x="gen", gen=true_x)
    ch_donor = ChainSeq(ds, rows, S, X, T, x="gen", gen=donor_x)
    none_, mid_true = ChainSeq(ds, rows, S, X, T, with_s=False), ChainSeq(ds, rows, S, X, T, with_s=False, x="row")
    checks = {
        "C1": all(_same(direct[i], tl["S"][i]) for i in range(n)),
        "C1_neg_differs": sum(not _same(direct[i], tl["X"][i]) for i in range(n)),
        "C2": all(_same(ch_true[i], orc[i]) for i in range(n)),
        "C2_neg_differs": sum(not _same(ch_donor[i], orc[i]) for i in range(n)),
        "C2_neg_expected": sum(not torch.equal(true_x[r], donor_x[r]) for r in rows),
        "C3": all(donor[r] != r for r in rows) and sorted(donor.values()) == rows,
        "C5_none": all(_same(none_[i], tl["none"][i]) for i in range(n)),
        "C5_mid_true": all(_same(mid_true[i], tl["X"][i]) for i in range(n)),
    }
    if rng_order.index(S) < rng_order.index(X):
        checks["C2b"] = all(_same(orc[i], tl["SX"][i]) for i in range(n))
    pd_ = [_prompt(direct[i], T) for i in range(n)]
    checks["C4_direct_is_build_prompt"] = all(
        torch.equal(p, G.build_prompt(ds, r, T, sources=[S])["prompt"]) for p, r in zip(pd_, rows))
    checks["C4_mid_prompt_is_build_prompt"] = all(
        torch.equal(G.build_prompt(ds, r, X, sources=[S])["prompt"],
                    torch.cat([ds._load_chunk(S, r), torch.tensor([get_modality(X).bo_id])])) for r in rows)
    checks["C4_neg_differs"] = sum(
        not torch.equal(orc[i]["input_ids"][:len(pd_[i])], pd_[i]) for i in range(n))
    # ⚠ C2's negative fails on a row only where the donor's X is token-identical to the row's
    # (e.g. two flat DEM tiles that both encode to one code). Those rows are listed; the
    # negative must fire on every other row.
    same_x = [(r, donor[r], int(len(torch.unique(true_x[r])))) for r in rows if torch.equal(true_x[r], donor_x[r])]
    checks["identical_donor_x"] = same_x
    bad = [k for k, v in checks.items() if (v is False)
           or (k in ("C1_neg_differs", "C4_neg_differs") and v != n)
           or (k == "C2_neg_differs" and v != checks["C2_neg_expected"])]
    print(f"controls on {n} rows: " + ", ".join(f"{k}={v}" for k, v in checks.items()), flush=True)
    if bad:
        raise SystemExit(f"CONTROLS FAILED: {bad}")
    if args.controls_only:
        return 0

    def gen_batches(prompts, target, mode="t1", cache=None):
        """Batches of 8, seed 42 per batch (D3.11). With `cache`, finished batches are saved
        every GEN_CHUNK batches and reloaded on restart; the batches are fixed, so a resumed
        stage generates exactly what an uninterrupted one would (up to kernel nondeterminism)."""
        done = {}
        if cache is not None and cache.exists():
            z = np.load(cache)
            done = {int(k[1:-4]): [torch.from_numpy(z[k][j, :z[f"b{k[1:-4]}_len"][j]].copy())
                                   for j in range(len(z[k]))] for k in z.files if k.endswith("_ids")}
            print(f"  resuming {cache.name}: {len(done)} batches already done", flush=True)
        n_new = 0
        for i in range(0, len(prompts), 8):
            if i in done:
                continue
            done[i] = G.generate(model, prompts[i:i + 8], target, slot_masked=True, seed=42, **MID_MODES[mode])
            n_new += 1
            if cache is not None and n_new % GEN_CHUNK == 0:
                arrs = {}
                for b, g in done.items():
                    w = max(len(x) for x in g)
                    ids = np.full((len(g), w), PAD_ID, dtype=np.int64)
                    for j, x in enumerate(g):
                        ids[j, :len(x)] = x.numpy()
                    arrs[f"b{b}_ids"], arrs[f"b{b}_len"] = ids, np.array([len(x) for x in g])
                save_npz(cache, **arrs)
        return [x for i in sorted(done) for x in done[i]]

    modes = args.mid_modes
    gen_x, okall = {}, np.ones(n, dtype=bool)
    for mode in modes:
      # ---- stage gen_mid<sfx>: X̂ from [S] alone
      pm = out / f"gen_mid{sfx(mode)}.npz"
      if not pm.exists():
        tg = time.perf_counter()
        built = [G.build_prompt(ds, r, X, sources=[S]) for r in rows]
        assert all(b["context"] == [S] for b in built)
        g = gen_batches([b["prompt"] for b in built], X, mode, cache=out / f"part_mid{sfx(mode)}.npz")
        st = G.score(g, [b["truth"] for b in built], X)
        eo = get_modality(X).eo_id
        ok = np.array([len(x) == XB + 1 and int(x[-1]) == eo for x in g])
        ids = np.full((n, XB + 1), PAD_ID, dtype=np.int64)
        for i, x in enumerate(g):
            ids[i, :min(len(x), XB + 1)] = x.numpy()[:XB + 1]
        grids, valid, rep = PD.to_grids(ids, X)
        st.update(seconds=round(time.perf_counter() - tg, 1), repair=rep,
                  dropped_not_196=[r for r, k in zip(rows, ok) if not k])
        st["mode"] = mode
        save_npz(pm, rows=np.array(rows), ids=ids, ok=ok, grids=grids, valid=valid,
                 stats=np.array(json.dumps(st, default=float)))
        print(f"{args.arm_tag} gen X̂={X} from {S} [{mode}]: {n} rows in {st['seconds']}s, {ok.sum()} well formed, "
              f"token accuracy {st['token_accuracy']:.4f}", flush=True)
      zm = np.load(pm)
      assert zm["rows"].tolist() == rows
      gen_x[mode] = {r: torch.from_numpy(zm["ids"][i, :XB]) for i, r in enumerate(rows) if zm["ok"][i]}
      okall &= zm["ok"].astype(bool)
    rv = [r for r, k in zip(rows, okall) if k]        # well formed in EVERY mode: all conditions pair

    sets = {"none": ChainSeq(ds, rv, S, X, T, with_s=False),
            "direct": ChainSeq(ds, rv, S, X, T),
            "oracle": ChainSeq(ds, rv, S, X, T, x="row"),
            "control": ChainSeq(ds, rv, S, X, T, x="donor", donor=donor),
            "mid_true": ChainSeq(ds, rv, S, X, T, with_s=False, x="row")}
    for mode in modes:
        sets[f"chained{sfx(mode)}"] = ChainSeq(ds, rv, S, X, T, x="gen", gen=gen_x[mode])
        sets[f"mid_gen{sfx(mode)}"] = ChainSeq(ds, rv, S, X, T, with_s=False, x="gen", gen=gen_x[mode])

    # ---- stages gen_<c>: T under direct / chained / oracle (T always at t1)
    for c in gen_conditions(modes):
        pc = out / f"gen_{c}.npz"
        if pc.exists():
            continue
        tg = time.perf_counter()
        prompts = [_prompt(sets[c][i], T) for i in range(len(rv))]
        truths = [ds._load_chunk(T, r)[1:-1] for r in rv]
        g = gen_batches(prompts, T, cache=out / f"part_{c}.npz")
        width = max(len(x) for x in g)
        ids = np.full((len(g), width), PAD_ID, dtype=np.int64)
        for i, x in enumerate(g):
            ids[i, :len(x)] = x.numpy()
        grids, valid, rep = PD.to_grids(ids, T)
        st = G.score(g, truths, T)
        st.update(seconds=round(time.perf_counter() - tg, 1), repair=rep,
                  prompt_len=int(np.median([len(p) for p in prompts])))
        save_npz(pc, rows=np.array(rv), grids=grids, valid=valid, stats=np.array(json.dumps(st, default=float)))
        print(f"{args.arm_tag} gen {T} | {c:8}: {len(rv)} rows in {st['seconds']}s, prompt {st['prompt_len']} "
              f"tokens, token accuracy {st['token_accuracy']:.4f}, repaired {rep['repaired_fraction']:.4f} "
              f"({time.perf_counter() - t0:.0f}s)", flush=True)

    # ---- stage ce: every condition, router wrapper on (as the grid; None for vanilla)
    pce = out / "ce_rows.npz"
    if not pce.exists():
        ov = TF.install_override(model, "router")
        ppart = out / "part_ce.npz"            # per-condition resume
        arrays = dict(np.load(ppart)) if ppart.exists() else {"rows": np.array(rv)}
        assert arrays["rows"].tolist() == rv
        for c in ce_conditions(modes):
            if f"{c}|ce" in arrays:
                continue
            dl = torch.utils.data.DataLoader(sets[c], batch_size=4, num_workers=args.num_workers,
                                             collate_fn=TF.trim_collate)
            r = TF.run_pass(model, dl, override=ov, keep_tokens=False, per_row_target=T)["rows"]
            arrays[f"{c}|ce"] = r["ce_sum"] / np.maximum(r["n"], 1)
            arrays[f"{c}|top1"] = r["top1"] / np.maximum(r["n"], 1)
            print(f"{args.arm_tag} ce {c:8} done ({time.perf_counter() - t0:.0f}s)", flush=True)
            save_npz(ppart, **arrays)
        save_npz(pce, **arrays)

    doc = {"arm_tag": args.arm_tag, "arm_config": args.arm_config, "run_dir": args.run_dir,
           "token_set": (cfg.get("multimodal") or {}).get("token_set", "original"),
           "checkpoint": args.checkpoint, "gpu": gpu, "chain": [S, X, T], "rows": len(rows),
           "rows_scored": len(rv), "seed": args.seed, "controls": checks, "mid_modes": modes,
           "generation": {"protocol": "slot-masked, seed 42 per batch of 8; target T=1.0; middle "
                                      + ", ".join(f"{m}={MID_MODES[m]}" for m in modes)}}
    save_json(out / "run.json", doc)
    print(f"-> {out}  ({time.perf_counter() - t0:.0f}s)", flush=True)
    return 0


# ----------------------------------------------------------------------------- decode (mor)

def decode_cmd(args) -> int:
    """Decode T under each generated condition plus T's true-token floor, and X̂ plus X's
    floor, with 12.6b's per-modality decoder setting; score against the original rasters."""
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import s12_decoded_eval as DE   # mor env: terratorch, decode_eo, clamp_test

    D, C, P, TK, CT = DE.D, DE.C, DE.P, DE.TK, DE.CT
    gpu = D.assert_gpu(args.allow_titanv)
    print(f"gpu {gpu}", flush=True)
    base = out_dir(args)
    modes = args.mid_modes
    for mod, files in ((args.target, [f"gen_{c}.npz" for c in gen_conditions(modes)]),
                       (args.mid, [f"gen_mid{sfx(m)}.npz" for m in modes])):
        tok = TK.build(mod, device=TK.DEVICE)
        sched = CT.scheduler_like(tok, **CT.VARIANTS["noclip"]) if DE.SETTING[mod] == "unclamped" else None
        for arm in args.arms:
            dst = base / arm / f"decoded_{mod}.npz"
            if dst.exists():
                continue
            ts = arm_token_set(base, arm)
            arrays = {}
            for f in files:
                z = np.load(base / arm / f)
                R = z["rows"]
                refs = [P.center_crop(a[0] if a.ndim == 4 else a).astype(np.float32)
                        for a in D.read_rasters(mod, R, ts)]
                name = f[4:-4]                                # gen_direct.npz -> direct
                if f"floor|rows" not in arrays:
                    truth = D.read_tokens(mod, R, ts)
                    e, eml, _ = DE.score(mod, DE.decode(tok, mod, truth, sched), refs)
                    arrays.update({"floor|rows": R, "floor|err": e, "floor|err_ml7": eml})
                    print(f"  {arm} {mod} floor: {e.mean():.4f} (ml7 {eml.mean():.4f}) n {len(R)}", flush=True)
                if not np.array_equal(arrays["floor|rows"], R):
                    raise SystemExit(f"{arm} {f}: rows differ from the floor's")
                e, eml, _ = DE.score(mod, DE.decode(tok, mod, z["grids"], sched), refs)
                arrays.update({f"{name}|rows": R, f"{name}|err": e, f"{name}|err_ml7": eml,
                               f"{name}|valid_frac": z["valid"].mean(1)})
                print(f"  {arm} {mod} {name:8}: {e.mean():.4f} (ml7 {eml.mean():.4f}) n {len(R)}", flush=True)
            save_npz(dst, **arrays)
            save_json(base / arm / f"decoded_{mod}.json", {"setting": DE.SETTING_TEXT[DE.SETTING[mod]],
                                                         "token_set": ts,
                                                         "decode": {"seed": DE.SEED, "batch": DE.BATCH,
                                                                    "timesteps": DE.STEPS}})
    print("decode done", flush=True)
    return 0


