def boot(x, key, seed=0, n_boot=10_000):
    rng = np.random.default_rng([seed, zlib.crc32(key.encode())])
    m = x[rng.integers(0, len(x), size=(n_boot, len(x)))].mean(1)
    lo, hi = np.percentile(m, [2.5, 97.5])
    return {"n": int(len(x)), "mean": float(x.mean()), "lo": float(lo), "hi": float(hi)}


def boot_ratio(num, den, key, seed=0, n_boot=10_000):
    """mean(num) / mean(den), scenes resampled jointly."""
    rng = np.random.default_rng([seed, zlib.crc32(key.encode())])
    idx = rng.integers(0, len(num), size=(n_boot, len(num)))
    r = num[idx].mean(1) / den[idx].mean(1)
    lo, hi = np.percentile(r, [2.5, 97.5])
    return {"mean": float(num.mean() / den.mean()), "lo": float(lo), "hi": float(hi)}


def fmt(b):
    return f"{b['mean']:+.4f} [{b['lo']:+.4f},{b['hi']:+.4f}]" + (" *" if b["lo"] > 0 or b["hi"] < 0 else "")


def analyze(args) -> int:
    base = out_dir(args)
    S, X, T = args.source, args.mid, args.target
    res, L = {"chain": [S, X, T]}, [f"Chain {S} -> {X} -> {T}   (* = 95% CI excludes 0; paired, scenes resampled)", ""]
    for arm in args.arms:
        d = base / arm
        run_doc = json.loads((d / "run.json").read_text())
        ce = np.load(d / "ce_rows.npz")
        modes = run_doc.get("mid_modes", ["t1"])
        r = {"checkpoint": run_doc["checkpoint"], "gpu": run_doc["gpu"], "rows": run_doc["rows"],
             "rows_scored": run_doc["rows_scored"], "mid_modes": modes, "mid_generation": {}}
        L.append(f"{arm} ({run_doc['checkpoint']}, {run_doc['gpu']}): {run_doc['rows_scored']} of "
                 f"{run_doc['rows']} rows scored")
        for m in modes:
            gst = json.loads(str(np.load(d / f"gen_mid{sfx(m)}.npz")["stats"]))
            r["mid_generation"][m] = {k: gst[k] for k in ("token_accuracy", "codes_used", "codes_used_truth",
                                                          "seconds", "dropped_not_196")}
            L.append(f"  X̂ = {X} from {S} [{m}]: token accuracy {gst['token_accuracy']:.4f}, codes used "
                     f"{gst['codes_used']} (truth {gst['codes_used_truth']}), dropped {len(gst['dropped_not_196'])}")
        # CE
        CEC = ce_conditions(modes)
        c = {k: ce[f"{k}|ce"] for k in CEC}
        r["ce_mean"] = {k: float(v.mean()) for k, v in c.items()}
        r["top1_mean"] = {k: float(ce[f"{k}|top1"].mean()) for k in CEC}
        L.append(f"  teacher-forced CE of the true {T} tokens, nats/token (top-1 %):")
        L.append("    " + "  ".join(f"{k} {r['ce_mean'][k]:.4f} ({100 * r['top1_mean'][k]:.1f})" for k in CEC))
        pairs = [("oracle", "direct"), ("control", "direct"), ("direct", "none"), ("mid_true", "none")]
        for m in modes:
            ch, mg = f"chained{sfx(m)}", f"mid_gen{sfx(m)}"
            pairs += [(ch, "direct"), (ch, "control"), (ch, "oracle"), (mg, "none"), (mg, "mid_true")]
        if len(modes) > 1:
            pairs += [(f"chained{sfx(m)}", "chained") for m in modes if m != "t1"]
        r["ce_paired"] = {f"{a}-{b}": boot(c[a] - c[b], f"{arm}|ce|{a}-{b}") for a, b in pairs}
        for a, b in pairs:
            L.append(f"    {a + ' − ' + b:28} {fmt(r['ce_paired'][f'{a}-{b}'])}")
        r["breakeven"] = boot_ratio(c["control"] - c["direct"], c["control"] - c["oracle"], f"{arm}|be")
        r["fidelity"] = {}
        for m in modes:
            ch = f"chained{sfx(m)}"
            r["fidelity"][m] = boot_ratio(c["control"] - c[ch], c["control"] - c["oracle"],
                                          f"{arm}|f" + ("" if m == "t1" else f"|{m}"))
            L.append(f"    fidelity [{m}] f = (control − chained)/(control − oracle) = {r['fidelity'][m]['mean']:.3f} "
                     f"[{r['fidelity'][m]['lo']:.3f},{r['fidelity'][m]['hi']:.3f}]")
        L.append(f"    break-even (control − direct)/(control − oracle) = {r['breakeven']['mean']:.3f} "
                 f"[{r['breakeven']['lo']:.3f},{r['breakeven']['hi']:.3f}]")
        # decoded
        GC = gen_conditions(modes)
        for mod, conds in ((T, GC), (X, [f"mid{sfx(m)}" for m in modes])):
            p = d / f"decoded_{mod}.npz"
            if not p.exists():
                L.append(f"  decoded {mod}: not decoded yet")
                continue
            z = np.load(p)
            unit = "misclassified pixel share" if mod == "LULC" else "MSE, z units²"
            key = "dec_target" if mod == T else "dec_mid"
            r[key] = {"unit": unit, "floor": float(z["floor|err"].mean()),
                      "floor_ml7": float(z["floor|err_ml7"].mean()),
                      "mean": {k: float(z[f"{k}|err"].mean()) for k in conds},
                      "mean_ml7": {k: float(z[f"{k}|err_ml7"].mean()) for k in conds}}
            L.append(f"  decoded {mod} ({unit}; true-token floor {r[key]['floor']:.4f}):  " + "  ".join(
                f"{k} {r[key]['mean'][k]:.4f}" for k in conds)
                + ("" if mod == "LULC" else "   ml7: " + "  ".join(f"{k} {r[key]['mean_ml7'][k]:.4f}" for k in conds)))
            if mod == T:
                rows = z["direct|rows"]
                assert all(np.array_equal(z[f"{k}|rows"], rows) for k in conds)
                r[key]["paired"] = {}
                dpairs = [("oracle", "direct")] + [(f"chained{sfx(m)}", b) for m in modes for b in ("direct", "oracle")] \
                    + [(f"chained{sfx(m)}", "chained") for m in modes if m != "t1" and "t1" in modes]
                for a, b in dpairs:
                    for col in ("err",) + (() if mod == "LULC" else ("err_ml7",)):
                        bb = boot(z[f"{a}|{col}"] - z[f"{b}|{col}"], f"{arm}|dec|{a}-{b}|{col}")
                        r[key]["paired"][f"{a}-{b}|{col}"] = bb
                        L.append(f"    {a + ' − ' + b:24} {col:7} {fmt(bb)}")
                if mod == "LULC":   # s12_decoded_eval: misclassified share = 5 x the one-hot MSE
                    r[key]["onehot_mse"] = {k: v / 5 for k, v in r[key]["mean"].items()}
                    L.append("    as MSE of the 10-class one-hot maps (= share / 5): " + "  ".join(
                        f"{k} {v:.4f}" for k, v in r[key]["onehot_mse"].items()) + f"  floor {r[key]['floor'] / 5:.4f}")
        res[arm] = r
        L.append("")
    save_json(base / f"chain_result{pair_sfx(args.arms)}.json", res)
    (base / f"chain_result{pair_sfx(args.arms)}.txt").write_text("\n".join(L) + "\n")
    print("\n".join(L))
    return 0


def figures_cmd(args) -> int:
    """`mor` env. (1) the effect of each context against the one-to-one cell, CE and decoded,
    both arms; (2) two illustration scenes, chosen by rule (true-token decode error closest
    to the median), every panel re-decoded exactly as scored (same batch of 4, same seed)."""
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import s12_decoded_eval as DE
    import matplotlib.pyplot as plt
    from matplotlib.patches import Patch

    D, P, TK, CT = DE.D, DE.P, DE.TK, DE.CT
    S, X, T = args.source, args.mid, args.target
    base = out_dir(args)
    A, B = args.arms
    ts = pair_token_set(base, args.arms)
    COL = {A: "#2a78d6", B: "#eb6834"}                 # grid_report.ARM_COLORS
    INK, INK2, SURF = "#0b0b0b", "#52514e", "#fcfcfb"

    # ---- (1) effects against the one-to-one cell
    ce_rows = [("chained", f"+ generated {X}"), ("oracle", f"+ true {X}"),
               ("control", f"+ another scene's {X}"), ("mid_true", f"true {X} alone (no {S})"),
               ("mid_gen", f"generated {X} alone")]
    dec_rows = [("chained", f"+ generated {X}"), ("oracle", f"+ true {X}")]
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12.5, 4.3), gridspec_kw={"width_ratios": [1.35, 1]})
    fig.patch.set_facecolor(SURF)
    for ax, rows_, unit in ((ax1, ce_rows, "ce"), (ax2, dec_rows, "dec")):
        ax.set_facecolor(SURF)
        for k, a in enumerate(args.arms):
            if unit == "ce":
                z = np.load(base / a / "ce_rows.npz")
                vals = [boot(z[f"{c}|ce"] - z["direct|ce"], f"{a}|fig|{c}") for c, _ in rows_]
            else:
                z = np.load(base / a / f"decoded_{T}.npz")
                vals = [{kk: 100 * v for kk, v in boot(z[f"{c}|err"] - z["direct|err"], f"{a}|figdec|{c}").items()
                         if kk != "n"} for c, _ in rows_]
            y = np.arange(len(rows_)) + (k - 0.5) * 0.28
            m = np.array([v["mean"] for v in vals])
            lo, hi = np.array([v["lo"] for v in vals]), np.array([v["hi"] for v in vals])
            ax.hlines(y, lo, hi, color=COL[a], lw=2)
            ax.plot(m, y, "o", ms=8, color=COL[a], mec=SURF, mew=2, label=a.upper())
            for yy, mm, hh in zip(y, m, hi):
                ax.text(hh, yy, f"  {mm:+.3f}" if unit == "ce" else f"  {mm:+.1f}", va="center",
                        fontsize=8.5, color=INK2)
        ax.axvline(0, color=INK2, lw=1, ls=(0, (3, 3)))
        ax.set_yticks(np.arange(len(rows_)))
        ax.set_yticklabels([lbl for _, lbl in rows_], fontsize=10, color=INK)
        ax.set_ylim(len(rows_) - 0.5, -0.5)
        ax.grid(axis="x", color="#e6e5e2", lw=0.8)
        ax.set_axisbelow(True)
        for s in ("top", "right", "left"):
            ax.spines[s].set_visible(False)
        ax.spines["bottom"].set_color("#b8b7b3")
        ax.tick_params(colors=INK2, labelsize=9, length=0)
    ax1.set_xlabel(f"Δ CE of the true {T} tokens vs {S} → {T} alone (nats/token; < 0 = better)",
                   fontsize=9.5, color=INK)
    ax2.set_xlabel(f"Δ misclassified pixels vs {S} → {T} alone (pp; < 0 = better)",
                   fontsize=9.5, color=INK)
    ax1.set_title("Teacher-forced CE (all conditions)", fontsize=11, color=INK, loc="left")
    ax2.set_title(f"Generated and decoded {T} (three conditions)", fontsize=11, color=INK, loc="left")
    ax1.legend(loc="upper left", frameon=False, fontsize=9.5)
    fig.text(0.01, 0.01, f"Dot: mean over scenes; bar: paired 95% bootstrap CI (10,000 resamples). "
             f"Dashed line: the one-to-one generation {S} → {T}. {S} rows only (ssl4eos12), checkpoint-3300.",
             fontsize=8.5, color=INK2)
    plt.tight_layout(rect=(0, 0.04, 1, 1))
    fig.savefig(base / f"fig_chain_effects{pair_sfx(args.arms)}.png", dpi=130, facecolor=SURF)
    plt.close(fig)

    # ---- (2) illustration scenes
    dz = {a: np.load(base / a / f"decoded_{T}.npz") for a in args.arms}
    fl = dict(zip(dz[A]["floor|rows"].tolist(), dz[A]["floor|err"].tolist()))
    common = set(dz[A]["direct|rows"].tolist()) & set(dz[B]["direct|rows"].tolist())
    med = float(np.median(list(fl.values())))
    # ⚠ ssl4eos12 carries the same location at several seasons (identical DEM tokens; worklog
    # 2026-10-07): skip a candidate whose true X duplicates a scene already drawn.
    xtok = np.load(D.token_root(ts) / DE.C.tok_dir_name(X) / "tokens.npy", mmap_mode="r")
    scenes = []
    for r in sorted((r for r in fl if r in common), key=lambda r: (abs(fl[r] - med), r)):
        if len(scenes) < args.n_scenes and not any(np.array_equal(xtok[r], xtok[q]) for q in scenes):
            scenes.append(r)
    tokT, tokX = TK.build(T, device=TK.DEVICE), TK.build(X, device=TK.DEVICE)
    sch = {m: (CT.scheduler_like(tk, **CT.VARIANTS["noclip"]) if DE.SETTING[m] == "unclamped" else None)
           for m, tk in ((T, tokT), (X, tokX))}

    def decoded_as_scored(mod, tok, npz, row, scored_err):
        """The row's panel, decoded inside the same batch of 4 as when it was scored."""
        rows = npz["rows"].tolist()
        i = rows.index(row)
        j = DE.BATCH * (i // DE.BATCH)
        out = DE.decode(tok, mod, npz["grids"][j:j + DE.BATCH], sch[mod])[i - j]
        ref = P.center_crop((lambda a: a[0] if a.ndim == 4 else a)(D.read_rasters(mod, np.array([row]), ts)[0])
                            ).astype(np.float32)
        e = float(DE.score(mod, out[None], [ref])[0][0])
        if scored_err is not None and abs(e - scored_err) > 1e-4:
            raise SystemExit(f"{mod} row {row}: re-decoded error {e:.5f} != scored {scored_err:.5f}")
        img = out.argmax(0).numpy() if mod == T and T == "LULC" else DE.display(mod, P.destandardize(out, mod).numpy())
        return img, e

    cols = ([f"{S}\n(source)", f"{X}\ntruth"] + [f"{X} generated\n{a.upper()}" for a in args.arms]
            + [f"{T}\ntruth"] + [f"{a.upper()}\n{lbl}" for a in args.arms
                                for lbl in (f"{S} → {T}", f"+ generated {X}", f"+ true {X}")])
    fig, axs = plt.subplots(len(scenes), len(cols), figsize=(1.62 * len(cols), 1.75 * len(scenes) + 1.25))
    fig.patch.set_facecolor(SURF)
    axs = np.atleast_2d(axs)
    classes = set()
    for i, r in enumerate(scenes):
        src, _ = DE.source_image(S, r, ts)
        xt, _ = DE.source_image(X, r, ts)
        tt, _ = DE.source_image(T, r, ts)
        panels = [(S, src, src, None), (X, xt, xt, None)]
        for a in args.arms:
            zm = np.load(base / a / "gen_mid.npz")
            ex = dict(zip(np.load(base / a / f"decoded_{X}.npz")["mid|rows"].tolist(),
                          np.load(base / a / f"decoded_{X}.npz")["mid|err"].tolist()))
            img, e = decoded_as_scored(X, tokX, zm, r, ex[r])
            panels.append((X, img, xt, f"MSE {e:.2g}"))
        panels.append((T, tt, tt, None))
        classes |= set(np.unique(tt).astype(int).tolist())
        for a in args.arms:
            for c in gen_conditions(["t1"]):
                zg = np.load(base / a / f"gen_{c}.npz")
                errs = dict(zip(dz[a][f"{c}|rows"].tolist(), dz[a][f"{c}|err"].tolist()))
                img, e = decoded_as_scored(T, tokT, zg, r, errs[r])
                classes |= set(np.unique(img).astype(int).tolist())
                panels.append((T, img, tt, f"{100 * e:.0f}% wrong"))
        for j, (mod, img, ref, lab) in enumerate(panels):
            ax = axs[i, j]
            ax.set_xticks([]); ax.set_yticks([])
            for s_ in ax.spines.values():
                s_.set_visible(False)
            DE.show(ax, mod, img, ref)
            if lab:
                ax.text(0.03, 0.04, lab, transform=ax.transAxes, fontsize=7.5, color=INK,
                        bbox=dict(boxstyle="round,pad=0.2", fc="#ffffffcc", ec="none"))
        axs[i, 0].set_ylabel(f"row {r}", fontsize=8.5, color=INK)
    for j, c in enumerate(cols):
        axs[0, j].set_title(c, fontsize=8.5, color=INK, pad=5)
    handles = [Patch(color=DE.LULC_CMAP.colors[k], label=DE.LULC_NAMES[k]) for k in sorted(classes)]
    fig.legend(handles=handles, loc="lower left", bbox_to_anchor=(0.005, 0.045), ncol=len(handles),
               frameon=False, fontsize=8)
    fig.text(0.01, 0.012, f"Scenes chosen by rule: the {len(scenes)} whose true-token {T} decode error is closest to "
             f"the median. Every panel is re-decoded exactly as scored. {X} panels: relief relative to each "
             f"image's own mean (absolute offset in the MSE label, σ²).", fontsize=8, color=INK2)
    plt.tight_layout(rect=(0, 0.11, 1, 1))
    fig.savefig(base / f"fig_chain_scenes{pair_sfx(args.arms)}.png", dpi=130, facecolor=SURF)
    plt.close(fig)
    print(f"-> {base}/fig_chain_effects{pair_sfx(args.arms)}.png, fig_chain_scenes{pair_sfx(args.arms)}.png (scenes {scenes})", flush=True)
    return 0


def slides_cmd(args) -> int:
    """`mor` env. The two figures of the chained-generation slides (Enric, 2026-10-08), for a chain
    run with several middle-step modes: (1) every context against the one-to-one cell, CE and decoded
    on SHARED rows, both arms; (2) the chain as a picture, one arm, middle step at t1, scenes by rule
    and re-decoded exactly as scored."""
