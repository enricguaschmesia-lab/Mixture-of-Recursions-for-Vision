#: How X̂ is decoded from [S]. "t1" is D3.11's protocol and keeps the original file and
#: condition names; any other mode gets its own suffix, on the SAME rows, so modes pair.
#: Only the middle step changes: T is always generated with "t1".
MID_MODES = {"t1": dict(do_sample=True, temperature=1.0), "t05": dict(do_sample=True, temperature=0.5),
             "greedy": dict(do_sample=False, temperature=1.0)}
GEN_CHUNK = int(os.environ.get("CHAIN_GEN_CHUNK", 4))      # batches of 8 between partial saves: a TITAN V stall costs at most 32 rows


def sfx(mode):
    return "" if mode == "t1" else f"_{mode}"


def ce_conditions(modes):
    return (["none", "direct"] + [f"chained{sfx(m)}" for m in modes] + ["oracle", "control", "mid_true"]
            + [f"mid_gen{sfx(m)}" for m in modes])


def gen_conditions(modes):
    return ["direct"] + [f"chained{sfx(m)}" for m in modes] + ["oracle"]


def out_dir(args) -> Path:
    return Path(args.out or REPORTS / f"chain_{args.source}_{args.mid}_{args.target}")


def pair_sfx(arms) -> str:
    """Suffix of the pair-level outputs at the chain root: '' for A10/B10 (their files keep their
    names), '_a10c_b10c' etc. otherwise, so a second pair never overwrites the first."""
    return "" if list(arms) == ["a10", "b10"] else "_" + "_".join(arms)


def arm_token_set(base: Path, arm: str) -> str:
    """The token set an arm's chain run was prompted with (run.json; absent = original)."""
    return json.loads((base / arm / "run.json").read_text()).get("token_set", "original")


def pair_token_set(base: Path, arms) -> str:
    """Arms drawn or compared together must share a token set: their floors and references differ."""
    sets = {arm_token_set(base, a) for a in arms}
    if len(sets) != 1:
        raise SystemExit(f"arms {list(arms)} were run on different token sets {sorted(sets)}")
    return sets.pop()


def save_npz(path: Path, **arrays):
    tmp = path.with_suffix(".tmp.npz")
    np.savez(tmp, **arrays)
    os.replace(tmp, path)


def save_json(path: Path, doc):
    tmp = path.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(doc, indent=1, default=float) + "\n")
    os.replace(tmp, path)


