#!/usr/bin/env python
"""Chained generation S -> X -> T for any (source, intermediate, target), scored by
teacher-forced CE AND by the decoded target against the real raster.

D3.15 (`s12_chains.py`) fixed the chain to S1 -> S2L2A -> {DEM, NDVI, LULC} and scored
CE only. This generalises it (Enric, 2026-10-07): the chain is chosen from the one-to-one
grids, and every target is also GENERATED under the main conditions and decoded, as in
12.6b. Per held-out row, the context for the target is:

  none      [T]                 the grid's ∅ row: TargetLast(sources=[])            CE
  direct    [S, T]              the one-to-one cell: TargetLast(sources=[S]) (C1)   CE + decoded
  chained   [S, X̂, T]           X̂ generated by the same arm from S alone            CE + decoded
  oracle    [S, X, T]           the true X: the most chaining could ever give       CE + decoded
  control   [S, X(donor), T]    a true X from ANOTHER row: extra tokens, no content CE
  mid_true  [X, T]              the second leg alone, true X                        CE
  mid_gen   [X̂, T]              the second leg alone, generated X                   CE

⚠ LAYOUT. X goes AFTER S, because it is generated from S. Training shuffles modality order,
so both orders are in distribution. When registry order already puts S before X, oracle is
also exactly TargetLast(sources=[S, X]); C2b checks that.

FIDELITY. f = (control − chained) / (control − oracle): the share of the wrong-X -> true-X
distance that X̂ recovers. Chaining gains on CE iff f exceeds the break-even
(control − direct) / (control − oracle).

GENERATION, D3.11's protocol: slot-masked, temperature 1.0, seed 42 per batch of 8. The
prompt is the exact prefix of the scored sequence up to <BO_T> (C4). A row whose X̂ is not
exactly 196 tokens is dropped from EVERY condition and counted.

CONTROLS, exact, before any GPU work, each with a negative counterpart that must fail:
  C1   direct == TargetLast(sources=[S])            neg: != TargetLast(sources=[X])
  C2   chained(X̂ := true X) == oracle               neg: chained(X̂ := donor X) != oracle
  C2b  oracle == TargetLast(sources=[S, X]) when registry order is S, X
  C3   the control's donors are a derangement
  C4   every generation prompt is the prefix of its scored sequence, through <BO_T>,
       and direct's equals build_prompt(sources=[S])  neg: direct's prompt is not oracle's prefix
  C5   none == TargetLast(sources=[]), mid_true == TargetLast(sources=[X])

Stages (resumable, each written atomically, skipped when done):
  run      .venv, GPU   gen_mid -> gen_{direct,chained,oracle} -> ce
  decode   `mor`, GPU   T under each condition + the true-token floor; X̂ + X's floor
                        (the 12.6b decoder setting per modality, s12_decoded_eval)
  analyze  .venv, CPU   paired bootstrap CIs -> chain_result.{txt,json}
  figures  `mor`, GPU   fig_chain_effects.png, fig_chain_scenes.png (scenes re-decoded as scored)

    CUDA_DEVICE_ORDER=PCI_BUS_ID CUDA_VISIBLE_DEVICES=$(python -m eo.train.gpu titanx) \
      python -X faulthandler eo/experiments/s12_chain_any.py run --arm-tag a10 \
        --arm-config eo_terramesh/arm_a10_mor --run-dir <run dir> \
        --source S1GRD --mid DEM --target LULC

Outputs under /data/enric/reports/chain_<S>_<X>_<T>/<arm>/.
"""
