#!/usr/bin/env python
"""Step 12, decoded: the one-to-one grid scored on DETOKENIZED images (Enric, 2026-10-06).

The teacher-forced CE grid (D3.13) never decodes. This adds the image-space view Enric
asked for on 2026-10-06: every one-to-one cell S -> T, plus the ∅ row, GENERATED by each
arm and decoded to pixels, scored by mean squared error against the original raster.
It is a second number beside CE, not a replacement (PHASE3_PLAN.md 12.6, worklog
2026-10-06).

Two halves, two environments (as Step 7):
  generate  .venv, GPU -- this script. Per arm, per cell, the generated target tokens
            as LOCAL codebook grids + valid masks (prepare_decode.to_grids), per target.
  decode    `mor`, GPU -- eo/experiments/s12_decoded_eval.py. Decodes with ONE decoder
            setting per column, scores, draws the illustrations.
  report    .venv, CPU -- this script. The MSE grid figure with paired CIs.

ROWS. Column T uses stratified_target_rows(..., T, 64): the head of the same
corpus-alternating sequence whose first 512 rows the CE grid used, so the two metrics
share scenes. Cell S -> T uses the rows of that list that carry S (S1GRD rows are
ssl4eos12-only and S1RTC rows majortom-only, so those cells have 32; the S1GRD and S1RTC
columns are single-corpus).

GENERATION. D3.11's protocol: slot-masked, temperature 1.0, seed 42 per batch of 8;
prompt build_prompt(sources=[S]) or sources=[] for ∅ (gate W13). Both arms on the same
card, the same rows, the same code.

    CUDA_DEVICE_ORDER=PCI_BUS_ID CUDA_VISIBLE_DEVICES=$(python -m eo.train.gpu titanv) \
      python eo/experiments/s12_decoded_grid.py generate --arm-tag a10 \
        --arm-config eo_terramesh/arm_a10_mor --run-dir <run dir> --expect-gpu "TITAN V"
    python eo/experiments/s12_decoded_grid.py report

Generations under /data/enric/generations/s12_decoded/<arm>/<T>/; report under
/data/enric/reports/decoded_grid/. Runs in `.venv`; never imports terratorch.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
os.environ.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")

import numpy as np  # noqa: E402
import torch  # noqa: E402

from eo.data.eo_vocab import IMAGE_MODALITIES, MODALITIES, PAD_ID, get_modality  # noqa: E402
from eo.data.eval_split import load_eval_rows, load_row_table  # noqa: E402
from eo.eval import teacher_forced as TF  # noqa: E402

ROOT = os.environ.get("TERRAMESH_TOK_ROOT", "/data/enric/data/TerraMesh/val")
GEN = Path("/data/enric/generations/s12_decoded")
REPORT = Path("/data/enric/reports/decoded_grid")
TARGETS, SOURCES = list(IMAGE_MODALITIES), list(MODALITIES)
HOLES = {"S1GRD->S1RTC", "S1RTC->S1GRD"}
ROWS_PER_COLUMN = 64


def cells_of(T):
    """The column's cells, one-to-one sources first (registry order), then ∅."""
    return [s for s in SOURCES if s != T and f"{s}->{T}" not in HOLES] + ["none"]


def generate(args) -> int:
    from eo.generate import conditional as G
    import prepare_decode as PD
    if torch.cuda.device_count() != 1:
        raise SystemExit("pin exactly one GPU")
    gpu = torch.cuda.get_device_name(0)
    if args.expect_gpu not in gpu:
        raise SystemExit(f"CUDA sees {gpu!r}, expected {args.expect_gpu!r}")
    torch.manual_seed(42)
    model, cfg = G.build_model(args.arm_config, str(Path(args.run_dir) / args.checkpoint))
    ds, _ = TF.eval_loader(cfg, num_workers=0)
    eval_rows, corpus = load_eval_rows(root_dir=ROOT), load_row_table(ROOT).corpus.values
    t0 = time.perf_counter()
    for T in (args.targets or TARGETS):
        out = Path(args.out) / args.arm_tag / T
        if (out / "manifest.json").exists():
            print(f"[skip] {args.arm_tag} {T}: done", flush=True)
            continue
        out.mkdir(parents=True, exist_ok=True)
        R = TF.stratified_target_rows(ds, eval_rows, corpus, T, args.rows)
        arrays, man = {"column_rows": np.array(R)}, {
            "arm_tag": args.arm_tag, "arm_config": args.arm_config, "checkpoint": args.checkpoint,
            "run_dir": args.run_dir, "gpu": gpu, "target": T, "seed": 42, "temperature": 1.0,
            "slot_masked": True, "batch": 8, "column_rows_corpus": {
                c: int(sum(corpus[r] == c for r in R)) for c in ("majortom", "ssl4eos12")},
            "cells": {}}
        for S in cells_of(T):
            rows = R if S == "none" else [r for r in R if S in ds.present_modalities(r)]
            built = [G.build_prompt(ds, r, T, sources=[] if S == "none" else [S]) for r in rows]
            assert all(b["context"] == ([] if S == "none" else [S]) for b in built)
            gen, tg = [], time.perf_counter()
            for i in range(0, len(built), 8):
                gen += G.generate(model, [b["prompt"] for b in built[i:i + 8]], T,
                                  do_sample=True, temperature=1.0, slot_masked=True, seed=42)
            width = max(len(g) for g in gen)
            ids = np.full((len(gen), width), PAD_ID, dtype=np.int64)
            for i, g in enumerate(gen):
                ids[i, :len(g)] = g.numpy()
            grids, valid, rep = PD.to_grids(ids, T)
            st = G.score(gen, [b["truth"] for b in built], T)
            arrays.update({f"{S}|rows": np.array(rows), f"{S}|grids": grids, f"{S}|valid": valid})
            man["cells"][S] = {"n": len(rows), "seconds": round(time.perf_counter() - tg, 1),
                               "repair": rep, "token_accuracy": st["token_accuracy"],
                               "stopped_at_exact_length": st["stopped_at_exact_length"],
                               "codes_used": st["codes_used"], "codes_used_truth": st["codes_used_truth"]}
            print(f"{args.arm_tag} {S:>6}->{T:<5} n {len(rows):3d}  {man['cells'][S]['seconds']:6.1f}s  "
                  f"repaired {rep['repaired_fraction']:.4f}  token acc {st['token_accuracy']:.4f}  "
                  f"({time.perf_counter() - t0:.0f}s)", flush=True)
        tmp = out / "cells.tmp.npz"
        np.savez(tmp, **arrays)
        os.replace(tmp, out / "cells.npz")
        (out / "manifest.json").write_text(json.dumps(man, indent=1) + "\n")   # last: the done marker
    print(f"-> {Path(args.out) / args.arm_tag}", flush=True)
    return 0


def report(args) -> int:
    """MSE grid figure from s12_decoded_eval.py's errors, paired by row like the CE grid."""
    global REPORT
    REPORT = Path(args.root)
    import grid_report as GR
    import matplotlib.pyplot as plt
    from matplotlib.colors import Normalize, TwoSlopeNorm

    arms = args.arms
    A, B = arms
    err, unit, setting = {}, {}, {}
    for T in TARGETS:
        p = REPORT / T / "errors.npz"
        if not p.exists():
            raise SystemExit(f"no decoded errors for {T} yet ({p})")
        err[T] = np.load(p)
        doc = json.loads((REPORT / T / "decoded.json").read_text())
        unit[T], setting[T] = doc["unit"], doc["decoder_setting"]
    rows = SOURCES + ["none", "ceiling"]
    res = {"arms": arms, "cells": {}, "unit": unit, "decoder_setting": setting}

    def get(T, arm, S):
        z = err[T]
        key = f"ceiling|{T}" if S == "ceiling" else f"{arm}|{S}"
        if f"{key}|{args.metric}" not in z.files:
            return None, None
        return z[f"{key}|rows"], z[f"{key}|{args.metric}"].astype(np.float64)

    for T in TARGETS:
        zr, ze = get(T, A, "none")
        for S in cells_of(T) + ["ceiling"]:
            c = {}
            for arm in arms:
                r, e = get(T, arm, S)
                c[arm] = {"n": int(len(e)), "mean": float(e.mean())}
                if S not in ("none", "ceiling"):
                    rz, ez = get(T, arm, "none")
                    pos = np.searchsorted(rz, r)
                    assert np.array_equal(rz[pos], r), f"{S}->{T}: rows not in the ∅ cell"
                    g = e - ez[pos]
                    c[arm]["gain_rel"] = float(g.mean() / ez[pos].mean())
                    c[arm]["gain"] = GR.boot(g, f"dec-gain|{arm}|{S}->{T}", 0, 10_000)
            if S != "ceiling":
                ra, ea = get(T, A, S)
                rb, eb = get(T, B, S)
                assert np.array_equal(ra, rb), f"{S}->{T}: arms on different rows"
                d = GR.boot(ea - eb, f"dec-paired|{S}->{T}", 0, 10_000)
                d["rel"] = float((ea - eb).mean() / eb.mean())
                c["paired"] = d
            res["cells"][f"{S}->{T}"] = c

    def M(f):
        out = np.full((len(rows), len(TARGETS)), np.nan)
        for i, S in enumerate(rows):
            for j, T in enumerate(TARGETS):
                c = res["cells"].get(f"{S}->{T}")
                if c is not None:
                    v = f(c)
                    out[i, j] = np.nan if v is None else v
        return out

    fig, axs = plt.subplots(2, 3, figsize=(18, 11.5), layout="constrained")
    fig.patch.set_facecolor(GR.SURFACE)
    labels = {"ceiling": "true tokens, decoded", **GR.LABEL}
    GR.LABEL.update(labels)
    for k, arm in enumerate(arms):
        MA = M(lambda c, arm=arm: c[arm]["mean"])
        # one colour scale per COLUMN (units differ: z² vs misclassified share); text carries values
        Mn = (MA - np.nanmin(MA, 0)) / (np.nanmax(MA, 0) - np.nanmin(MA, 0))
        GR._heatmap(axs[0, k], np.where(np.isnan(MA), np.nan, Mn), rows, GR.SEQ, Normalize(0, 1),
                    lambda v: "", f"{arm}: decoded error per cell (colour scaled per column)")
        for i in range(MA.shape[0]):           # the values, over the per-column colours
            for j in range(MA.shape[1]):
                if np.isfinite(MA[i, j]):
                    axs[0, k].text(j, i, f"{MA[i, j]:.3f}", ha="center", va="center", fontsize=7.5,
                                   color="#ffffff" if Mn[i, j] > 0.55 else GR.INK)
    DR = M(lambda c: 100 * c["paired"]["rel"] if "paired" in c else None)
    XD = M(lambda c: float(c["paired"]["lo"] > 0 or c["paired"]["hi"] < 0) if "paired" in c else None) == 1
    lim = min(50.0, max(2.0, float(np.nanmax(np.abs(DR)))))      # one outlier (∅ -> DEM) must not wash out the rest
    GR._heatmap(axs[0, 2], DR, rows, GR.DIV, TwoSlopeNorm(0, -lim, lim), lambda v: f"{v:+.1f}%",
                f"{A} − {B}, paired, relative to {B} (outlined: CI excludes 0; colour saturates at ±{lim:.0f}%)",
                outline=XD, cbar_label=f"% of {B}'s error  (blue: {A} lower)", fig=fig)
    for k, arm in enumerate(arms):
        G_ = M(lambda c, arm=arm: 100 * c[arm]["gain_rel"] if "gain_rel" in c[arm] else None)[:-2]
        XG = M(lambda c, arm=arm: float(c[arm]["gain"]["lo"] > 0) if "gain" in c[arm] else None)[:-2] == 1
        glim = max(5.0, float(np.nanmax(np.abs(G_))))
        GR._heatmap(axs[1, k], G_, rows[:-2], GR.DIV, TwoSlopeNorm(0, -glim, glim), lambda v: f"{v:+.0f}%",
                    f"{arm}: change in error vs ∅, same scenes (dashed: CI entirely > 0)",
                    outline=XG, outline_ls="--", cbar_label="% of the ∅ error (blue: the source helps)",
                    fig=fig if k == 1 else None)
    ax = axs[1, 2]
    ax.axis("off")
    lines = ["Generated by each arm (checkpoint-3300), decoded, compared",
             "with the original raster. One decoder setting per column:"] + \
        [f"  {T}: {setting[T]}" for T in TARGETS] + \
        ["", "Error: mean squared error in standardized (z) units,",
         "all bands, all valid pixels, every scene (no |z| filter).",
         "LULC: share of misclassified pixels (= MSE of the one-hot",
         "class maps × 5).",
         "'true tokens, decoded': the tokenizer's floor for the column.",
         "", "64 scenes per column (the CE grid's first 64); S1GRD/S1RTC",
         "sources: 32. Sampling: slot-masked, T = 1, seed 42.",
         "", "⚠ Single sampled generation per scene: decoded error mixes",
         "  the model's distribution with sampling noise. CE does not."]
    ax.text(0, 1, "\n".join(lines), va="top", ha="left", fontsize=8.5, color=GR.INK_2,
            transform=ax.transAxes)
    GR._title(fig, "One-to-one generation, decoded: error against the real image (checkpoint-3300)",
              "Rows: the source given (then generated). Columns: the generated target. "
              "Paired comparisons on identical scenes; CIs are 10,000-resample bootstraps over scenes.")
    sfx = "" if args.metric == "err" else "_ml7"
    GR._save(fig, REPORT / f"fig_decoded_grid{sfx}.png")
    (REPORT / f"decoded_grid{sfx}.json").write_text(json.dumps(res, indent=1) + "\n")
    print(f"-> {REPORT / f'fig_decoded_grid{sfx}.png'}")
    return 0


def rerun(args) -> int:
    """How much does ONE sampled generation per scene move a cell's decoded error?

    A10's S2L2A, S1GRD and S1RTC columns were generated twice: on the TITAN V before it
    stalled (kept in titanv_aborted_2026-10-06/), and on the Titan X (the reported run). Same
    model, same scenes, same protocol and seeds; only the card's numerics differ, which gives
    different draws. Both were decoded on the Titan X with the same settings. The paired
    run-to-run difference per cell is the noise floor against which an A10 - B10 decoded
    difference has to be read."""
    import grid_report as GR
    old_root = REPORT / "titanv_aborted_2026-10-06"
    res = {}
    for T in TARGETS:
        po, pn = old_root / T / "errors_a10.npz", REPORT / T / "errors_a10.npz"
        if not (po.exists() and pn.exists()):
            continue
        zo, zn = np.load(po), np.load(pn)
        pb = REPORT / T / "errors_b10.npz"
        zb = np.load(pb) if pb.exists() else None
        for S in cells_of(T):
            ro, eo_ = zo[f"a10|{S}|rows"], zo[f"a10|{S}|{args.metric}"].astype(np.float64)
            rn, en = zn[f"a10|{S}|rows"], zn[f"a10|{S}|{args.metric}"].astype(np.float64)
            assert np.array_equal(ro, rn), f"{S}->{T}: the two runs used different rows"
            c = {"n": int(len(en)), "run_titanv": float(eo_.mean()), "run_titanx": float(en.mean()),
                 "rerun": GR.boot(en - eo_, f"rerun|{S}->{T}", 0, 10_000),
                 "scene_corr": float(np.corrcoef(eo_, en)[0, 1])}
            if zb is not None:
                c["a10_minus_b10"] = GR.boot(en - zb[f"b10|{S}|{args.metric}"].astype(np.float64),
                                             f"dec-paired|{S}->{T}", 0, 10_000)
            res[f"{S}->{T}"] = c
    sfx = "" if args.metric == "err" else "_ml7"
    (REPORT / f"rerun{sfx}.json").write_text(json.dumps(res, indent=1) + "\n")
    print(f"{'cell':16}{'n':>4}{'TITAN V run':>13}{'Titan X run':>13}{'rerun diff [95% CI]':>28}"
          f"{'A10-B10 [95% CI]':>28}")
    for k, c in res.items():
        r, ab = c["rerun"], c.get("a10_minus_b10")
        print(f"{k:16}{c['n']:4d}{c['run_titanv']:13.3f}{c['run_titanx']:13.3f}"
              f"{r['mean']:+12.3f} [{r['lo']:+.3f},{r['hi']:+.3f}]"
              + (f"{ab['mean']:+12.3f} [{ab['lo']:+.3f},{ab['hi']:+.3f}]" if ab else ""))
    return 0


def main() -> int:
    global REPORT
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("generate")
    g.add_argument("--arm-tag", required=True)
    g.add_argument("--arm-config", required=True)
    g.add_argument("--run-dir", required=True)
    g.add_argument("--checkpoint", default="checkpoint-3300")
    g.add_argument("--targets", nargs="*", default=None)
    g.add_argument("--expect-gpu", default="TITAN V")
    g.add_argument("--rows", type=int, default=ROWS_PER_COLUMN, help="per column (smoke tests only)")
    g.add_argument("--out", default=str(GEN))
    r = sub.add_parser("report")
    r.add_argument("--arms", nargs=2, default=["a10", "b10"])
    r.add_argument("--root", default=str(REPORT))
    r.add_argument("--metric", choices=["err", "err_ml7"], default="err",
                   help="err: plain MSE (headline); err_ml7: after the 7x7 multilook")
    q = sub.add_parser("rerun")
    q.add_argument("--root", default=str(REPORT))
    q.add_argument("--metric", choices=["err", "err_ml7"], default="err")
    args = ap.parse_args()
    if args.cmd == "rerun":
        REPORT = Path(args.root)
        return rerun(args)
    return generate(args) if args.cmd == "generate" else report(args)


if __name__ == "__main__":
    raise SystemExit(main())
