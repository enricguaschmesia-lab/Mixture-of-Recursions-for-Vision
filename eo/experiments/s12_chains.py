#!/usr/bin/env python
"""Step 12.5 (D3.15): chained generation, S1 -> S2 -> target, scored by teacher-forced CE.

Is DEM predicted better through a GENERATED S2 than directly from S1? The analogue of
TerraMind's Thinking-in-Modalities (PHASE3_PLAN.md 12.5). Per held-out row, the
context for the TRUE target tokens is:

  direct    [S1, T]               the baseline: TargetLast(sources=[S1]) exactly (C1)
  chained   [S1, Ŝ2, T]           Ŝ2 generated by the same arm from S1 alone
  oracle    [S1, S2, T]           the true S2: the most chaining could ever give
  control   [S1, S2(donor), T]    a true S2 from ANOTHER row of the same set. If it beats
                                  direct, the gain comes from extra tokens, not content

⚠ LAYOUT. chained, oracle and control put S2 AFTER S1. Registry order would put S2
first, but S2 is generated FROM S1, so it follows it, as it does in generation.
Training shuffles modality order, so both layouts are in distribution; all three
conditions share this one, so they differ only in what the S2 tokens are.

TARGETS. DEM is the question. NDVI is the POSITIVE CONTROL: NDVI is a function of
S2, so chaining must help it if Ŝ2 is any good; if it does not, a null on DEM means
nothing. LULC is the [P] case (per-pixel class; a preview of S1 -> S2 -> BEN).
Prior, written in the plan before looking: a small effect on DEM.

ROWS. Per S1 variant (S1GRD rows are ssl4eos12-only, S1RTC majortom-only, so the two
are reported separately), 64 held-out rows carrying S1, S2L2A, DEM, NDVI and LULC: a
seeded sample (seed 0), the same rows for every target and both arms.

GENERATION, D3.11's protocol: slot-masked, temperature 1.0, seed 42 per batch of 8,
prompt build_prompt(sources=[S1]) = [S1 chunk, <BO_S2L2A>] (gate W13: the prefix of
the teacher-forced layout). A row whose Ŝ2 is not exactly 196 tokens is dropped from
EVERY condition, so all comparisons stay paired, and counted.

CONTROLS, exact, before anything is generated or scored:
  C1  direct's sequence == TargetLast(sources=[S1])'s, token for token, every row
  C2  chained with the TRUE S2 body in place of Ŝ2 == oracle, token for token
  C3  the control's donors are a derangement: no row is its own donor

    CUDA_DEVICE_ORDER=PCI_BUS_ID CUDA_VISIBLE_DEVICES=$(python -m eo.train.gpu titanx) \
      python eo/experiments/s12_chains.py run --arm-tag a10 \
        --arm-config eo_terramesh/arm_a10_mor --run-dir <run dir>
    python eo/experiments/s12_chains.py analyze

Outputs under /data/enric/reports/chains/. Runs in `.venv`; never imports terratorch.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time
import zlib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
os.environ.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")

import numpy as np  # noqa: E402
import torch  # noqa: E402

from eo.data.eo_vocab import IMAGE_MODALITIES, MODALITY_TO_ID, PAD_ID, get_modality  # noqa: E402
from eo.data.eval_split import load_eval_rows  # noqa: E402
from eo.eval import teacher_forced as TF  # noqa: E402

ROOT = os.environ.get("TERRAMESH_TOK_ROOT", "/data/enric/data/TerraMesh/val")
OUT = Path("/data/enric/reports/chains")
VARIANTS = ["S1GRD", "S1RTC"]
TARGETS = ["DEM", "NDVI", "LULC"]
NEEDED = ["S2L2A", "DEM", "NDVI", "LULC"]
CONDITIONS = ["direct", "chained", "oracle", "control"]
S2_BODY = get_modality("S2L2A").tokens_per_sample


class ChainSeq(torch.utils.data.Dataset):
    """[S1, (S2 from: row | donor | generated), T] or [S1, T], assembled exactly as
    TargetLast assembles a row (same assemble_sequence arguments)."""

    def __init__(self, base, rows, v, target, s2=None, donor=None, gen=None):
        self.base, self.rows, self.v, self.target = base, list(rows), v, target
        self.s2, self.donor, self.gen = s2, donor, gen       # s2 in {None, row, donor, gen}

    def __len__(self):
        return len(self.rows)

    def _s2_chunk(self, row):
        if self.s2 == "row":
            return self.base._load_chunk("S2L2A", row)
        if self.s2 == "donor":
            return self.base._load_chunk("S2L2A", self.donor[row])
        info = get_modality("S2L2A")
        return torch.cat([torch.tensor([info.bo_id]), self.gen[row].long(), torch.tensor([info.eo_id])])

    def __getitem__(self, i):
        from lm_dataset.sequence_assembly import assemble_sequence
        row = self.rows[i]
        mods = [self.v] + (["S2L2A"] if self.s2 else []) + [self.target]
        chunks = [self.base._load_chunk(self.v, row)] + ([self._s2_chunk(row)] if self.s2 else []) \
            + [self.base._load_chunk(self.target, row)]
        return assemble_sequence(
            chunks=chunks, chunk_modality_ids=[MODALITY_TO_ID[m] for m in mods],
            chunk_shufflable=[m in IMAGE_MODALITIES for m in mods],
            max_length=self.base.max_length, pad_id=PAD_ID,
            rng=np.random.default_rng(0), shuffle_image_patches=False)


def same(a, b):
    return set(a) == set(b) and all(torch.equal(a[k], b[k]) for k in a)


def pick_rows(ds, v, n, seed):
    cand = [int(r) for r in load_eval_rows(root_dir=ROOT)
            if all(m in ds.present_modalities(int(r)) for m in [v] + NEEDED)]
    rng = np.random.default_rng([seed, zlib.crc32(v.encode())])
    return sorted(int(r) for r in rng.choice(cand, size=min(n, len(cand)), replace=False)), len(cand)


def derangement(rows, key, seed):
    rng = np.random.default_rng([seed, zlib.crc32(key.encode())])
    p = [rows[i] for i in rng.permutation(len(rows))]
    return {p[i]: p[(i + 1) % len(p)] for i in range(len(p))}


def per_row(model, ov, dset, T, workers):
    if ov is not None:
        TF.install_override(model, "router")
    dl = torch.utils.data.DataLoader(dset, batch_size=4, num_workers=workers,
                                     collate_fn=TF.trim_collate)
    r = TF.run_pass(model, dl, override=ov, keep_tokens=False, per_row_target=T)["rows"]
    return r["ce_sum"] / np.maximum(r["n"], 1)


def run(args) -> int:
    from eo.generate import conditional as G
    if torch.cuda.device_count() != 1:
        raise SystemExit("pin exactly one GPU")
    gpu = torch.cuda.get_device_name(0)
    if args.expect_gpu not in gpu:
        raise SystemExit(f"CUDA sees {gpu!r}, expected {args.expect_gpu!r}")
    torch.manual_seed(42)
    model, cfg = G.build_model(args.arm_config, str(Path(args.run_dir) / args.checkpoint))
    ds, _ = TF.eval_loader(cfg, num_workers=args.num_workers)
    out = Path(args.out) / args.arm_tag
    out.mkdir(parents=True, exist_ok=True)
    t0 = time.perf_counter()

    rows, donors, n_cand = {}, {}, {}
    for v in VARIANTS:
        rows[v], n_cand[v] = pick_rows(ds, v, args.rows, args.seed)
        donors[v] = derangement(rows[v], f"control|{v}", args.seed)
        # C3, then C1 and C2 on every row and target, before any GPU work
        if any(donors[v][r] == r for r in rows[v]) or sorted(donors[v].values()) != rows[v]:
            raise SystemExit(f"C3 FAILED: {v} donors are not a derangement")
        true_s2 = {r: ds._load_chunk("S2L2A", r)[1:-1] for r in rows[v]}
        for T in TARGETS:
            direct, tl = ChainSeq(ds, rows[v], v, T), TF.TargetLast(ds, rows[v], T, sources=[v])
            if not all(same(direct[i], tl[i]) for i in range(len(rows[v]))):
                raise SystemExit(f"C1 FAILED: direct != TargetLast(sources=[{v}]) for {T}")
            ch, orc = ChainSeq(ds, rows[v], v, T, s2="gen", gen=true_s2), ChainSeq(ds, rows[v], v, T, s2="row")
            if not all(same(ch[i], orc[i]) for i in range(len(rows[v]))):
                raise SystemExit(f"C2 FAILED: chained(true S2) != oracle for {v} -> {T}")
        print(f"controls {v}: C1, C2, C3 exact on {len(rows[v])} rows "
              f"(of {n_cand[v]} carrying {v} + {'/'.join(NEEDED)})", flush=True)

    # generation: Ŝ2 from S1 alone, D3.11's protocol
    gen, gstats, arrays = {}, {}, {}
    for v in VARIANTS:
        built = [G.build_prompt(ds, r, "S2L2A", sources=[v]) for r in rows[v]]
        assert all(b["context"] == [v] for b in built)
        out_ids, tg = [], time.perf_counter()
        for i in range(0, len(built), 8):
            out_ids += G.generate(model, [b["prompt"] for b in built[i:i + 8]], "S2L2A",
                                  do_sample=True, temperature=1.0, slot_masked=True, seed=42)
        st = G.score(out_ids, [b["truth"] for b in built], "S2L2A")
        st["seconds"] = round(time.perf_counter() - tg, 1)
        eo = get_modality("S2L2A").eo_id
        ok = [len(g) == S2_BODY + 1 and int(g[-1]) == eo for g in out_ids]
        gen[v] = {r: g[:-1] for r, g, k in zip(rows[v], out_ids, ok) if k}
        st["dropped_not_196"] = [r for r, k in zip(rows[v], ok) if not k]
        gstats[v] = st
        arrays[f"{v}|gen_rows"] = np.array(rows[v])
        arrays[f"{v}|gen_ids"] = np.stack([np.pad(g.numpy(), (0, S2_BODY + 1 - len(g)), constant_values=PAD_ID)
                                           [:S2_BODY + 1] for g in out_ids])
        print(f"{args.arm_tag} generated Ŝ2 from {v}: {len(rows[v])} rows in {st['seconds']}s, "
              f"{sum(ok)} exactly 196 tokens, token accuracy {st['token_accuracy']:.4f}", flush=True)

    # scoring: every condition on the rows whose Ŝ2 is well formed. The router wrapper
    # goes on only now: generation ran on the bare model, as D3.11's did, and scoring
    # runs with the wrapper in router mode, as the grid does (None for vanilla).
    ov = TF.install_override(model, "router")
    for v in VARIANTS:
        rv = [r for r in rows[v] if r in gen[v]]
        for T in TARGETS:
            sets = {"direct": ChainSeq(ds, rv, v, T),
                    "chained": ChainSeq(ds, rv, v, T, s2="gen", gen=gen[v]),
                    "oracle": ChainSeq(ds, rv, v, T, s2="row"),
                    "control": ChainSeq(ds, rv, v, T, s2="donor", donor=donors[v])}
            arrays[f"{v}->{T}|rows"] = np.array(rv)
            for c in CONDITIONS:
                arrays[f"{v}->{T}|{c}"] = per_row(model, ov, sets[c], T, args.num_workers)
            m = {c: float(arrays[f"{v}->{T}|{c}"].mean()) for c in CONDITIONS}
            print(f"{args.arm_tag} {v}->{T:5} n {len(rv)}  " + "  ".join(f"{c} {m[c]:.4f}" for c in CONDITIONS)
                  + f"  ({time.perf_counter() - t0:.0f}s)", flush=True)

    doc = {"arm_tag": args.arm_tag, "arm_config": args.arm_config, "run_dir": args.run_dir,
           "checkpoint": args.checkpoint, "gpu": gpu, "rows_per_variant": args.rows, "seed": args.seed,
           "candidates": n_cand, "generation": gstats, "seconds": round(time.perf_counter() - t0, 1)}
    tmp = out / "chains.tmp.npz"
    np.savez(tmp, **arrays)
    os.replace(tmp, out / "chains_rows.npz")
    tj = out / "chains.json.tmp"
    tj.write_text(json.dumps(doc, indent=1, default=float) + "\n")
    os.replace(tj, out / "chains.json")
    print(f"-> {out}", flush=True)
    return 0


def boot(x, key, seed, n_boot=10_000):
    rng = np.random.default_rng([seed, zlib.crc32(key.encode())])
    m = x[rng.integers(0, len(x), size=(n_boot, len(x)))].mean(1)
    lo, hi = np.percentile(m, [2.5, 97.5])
    return {"n": int(len(x)), "mean": float(x.mean()), "lo": float(lo), "hi": float(hi)}


def analyze(args) -> int:
    root = Path(args.out)
    res, lines = {}, []
    pairs = [("chained", "direct"), ("oracle", "direct"), ("control", "direct"), ("chained", "control")]
    for d in sorted(p for p in root.iterdir() if (p / "chains.json").exists()):
        doc, z = json.loads((d / "chains.json").read_text()), np.load(d / "chains_rows.npz")
        res[d.name] = {"checkpoint": doc["checkpoint"], "gpu": doc["gpu"], "generation": {}, "cells": {}}
        lines.append(f"{d.name} ({doc['checkpoint']}, {doc['gpu']})")
        for v in VARIANTS:
            g = doc["generation"][v]
            res[d.name]["generation"][v] = g
            lines.append(f"  Ŝ2 from {v}: {g['n_scenes']} rows, dropped (not 196 tokens) "
                         f"{len(g['dropped_not_196'])}, token accuracy {g['token_accuracy']:.4f}, "
                         f"codes used {g['codes_used']} (truth {g['codes_used_truth']})")
            for T in TARGETS:
                k = f"{v}->{T}"
                ce = {c: z[f"{k}|{c}"] for c in CONDITIONS}
                cell = {"n": int(len(ce["direct"])), "mean": {c: float(ce[c].mean()) for c in CONDITIONS}}
                for a, b in pairs:
                    cell[f"{a}-{b}"] = boot(ce[a] - ce[b], f"{d.name}|{k}|{a}-{b}", args.seed)
                cell["control_beats_direct"] = cell["control-direct"]["hi"] < 0
                cell["chaining_helps"] = cell["chained-direct"]["hi"] < 0
                res[d.name]["cells"][k] = cell
                lines.append(f"  {k:12} n {cell['n']:3d}  " + "  ".join(
                    f"{a}−{b} {cell[f'{a}-{b}']['mean']:+.4f} [{cell[f'{a}-{b}']['lo']:+.4f},{cell[f'{a}-{b}']['hi']:+.4f}]"
                    for a, b in pairs)
                    + ("  ⚠ CONTROL BEATS DIRECT" if cell["control_beats_direct"] else ""))
            pc = res[d.name]["cells"][f"{v}->NDVI"]["chaining_helps"]
            lines.append(f"  positive control ({v} -> S2 -> NDVI): chaining helps NDVI = {pc}"
                         + ("" if pc else "  ⚠ then a DEM null is uninformative"))
        lines.append("")
    (root / "chains_result.json").write_text(json.dumps(res, indent=1) + "\n")
    (root / "chains_result.txt").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run")
    r.add_argument("--arm-tag", required=True)
    r.add_argument("--arm-config", required=True)
    r.add_argument("--run-dir", required=True)
    r.add_argument("--checkpoint", default="checkpoint-3300")
    r.add_argument("--rows", type=int, default=64, help="per S1 variant")
    r.add_argument("--num-workers", type=int, default=4)
    r.add_argument("--seed", type=int, default=0)
    r.add_argument("--expect-gpu", default="TITAN X")
    a = sub.add_parser("analyze")
    a.add_argument("--seed", type=int, default=0)
    for p in (r, a):
        p.add_argument("--out", default=str(OUT))
    args = ap.parse_args()
    return run(args) if args.cmd == "run" else analyze(args)


if __name__ == "__main__":
    raise SystemExit(main())
