#!/usr/bin/env python
"""A2 Step 4.2: evaluate Routes B and C (docs/plans/a2_segmentation.md, Step 4.2, items 2-3; eo/eval/seg_routes.py).

  Route B's maps are generated by eval_seg.py generate (and gated by its cachecheck), unchanged: the alias cells_<task> is
  an ordinary map arm there. Its scoring is here, since there is no tokenizer to decode:
    score-cells --dirs <generate dir> [...]     (`.venv` or `a2seg`; CPU is enough)
        writes beside the codes: score.json, per_patch_cm.npy (one matrix per patch or tile) and pred.npy; a K > 1
        directory also gets k1/ (sample 0, a K = 1 run) and k1b/ (sample 1, Z9's functional control), as step52_score.py
    ceiling-cells --task T --out <dir>           the stored TRUE cells of T's val views through the same path

  Route C's maps are deterministic, made from a checkpoint and scored at once (the labels are eo/maps/sets' val set,
  sha256-checked; on RCP A2_MAPS_ROOT names its copy):
    head-predict --config eo_seg/s42_c_<task> --checkpoint <run>/checkpoint-N --override finetune.init_from=<base> \\
        --override seg_head.lr=<lr> --override seg.root=<root> [--variant full|wrong] --precision bf16|fp32 \\
        [--expect-gpu A100] --out <dir>        (`.venv`, one GPU)
        writes pred.npy (samples, native, native) uint8, record.json, then score.json and per_patch_cm.npy
    score-head --dirs <head-predict dir> [...]   re-scores pred.npy (the workstation's check of the RCP score)

All refuse a test split. Every record names the config, checkpoint, precision and git commit.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))


def _commit() -> str:
    return subprocess.run(["git", "-C", str(REPO), "rev-parse", "--short", "HEAD"], capture_output=True,
                          text=True).stdout.strip()


def _write(out: Path, rec: dict, cms: np.ndarray, pred: np.ndarray) -> None:
    out.mkdir(parents=True, exist_ok=True)
    np.save(out / "per_patch_cm.npy", cms)
    np.save(out / "pred.npy", pred)
    (out / "score.json").write_text(json.dumps(rec, indent=1, default=str) + "\n")
    r = rec["result"]
    print(f"{rec['task']} route {rec['route']} {rec.get('source', {}).get('variant', '')} K {rec.get('K', '-')}: mIoU "
          f"{r['mIoU']:.4f} (per-sample sum {rec['per_sample_sum_mIoU']:.4f}, {rec['samples']} samples), pixel "
          f"{r['pixel_acc']:.4f}, top class share {rec['pred_top_share']:.3f} -> {out}", flush=True)


def _views(ds, ids):
    return ds.views.set_index("view").loc[list(ids)].reset_index()


def cmd_score_cells(a) -> None:
    from eo.data import seg_dataset as SD
    from eo.eval import seg_routes as R
    dev = "cuda" if a.device == "cuda" else "cpu"
    for d in map(Path, a.dirs):
        rec = json.loads((d / "record.json").read_text())
        if rec["split"] != "val":
            raise PermissionError(f"{d}: split {rec['split']}")
        if rec.get("codes_order", "raster") != "raster":
            raise RuntimeError(f"{d}: codes stored in {rec.get('codes_order')} order, not raster")
        codes = np.load(d / "codes.npy")
        ds = SD.SegDataset(SD.SegSpec(rec["task"], rec["arm"], rec["frames"], rec["split"],
                                      map_order=rec.get("map_order", "raster")))
        views = _views(ds, rec["views"])
        jobs = [(codes, d, {})]
        if codes.shape[1] > 1:
            jobs += [(codes[:, :1], d / "k1", {"k": 1, "note": "sample 0 of the K run"}),
                     (codes[:, 1:2], d / "k1b", {"k": 1, "note": "sample 1 of the K run (Z9's functional control)"})]
        for c, out, extra in jobs:
            if (out / "score.json").exists() and (out / "per_patch_cm.npy").exists():
                print(f"skip {out}: scored already", flush=True)
                continue
            t0 = time.time()
            res, cms, pred = R.score_cells(rec["task"], c, views, device=dev)
            res.update({"source": dict(rec, **extra), "seconds": time.time() - t0, "fork_commit": _commit()})
            _write(out, res, cms, pred)


def cmd_ceiling_cells(a) -> None:
    from eo.data import map_vocab as MV, seg_dataset as SD
    from eo.eval import seg_routes as R
    frames = "p1" if a.task == "pastis" else "single"
    arm = MV.CELL_ARMS[a.task]
    ds = SD.SegDataset(SD.SegSpec(a.task, arm, frames, "val", map_order="nested"))
    codes = np.asarray(ds.maps[ds.views.view.values])
    t0 = time.time()
    res, cms, pred = R.score_cells(a.task, codes, ds.views, device="cpu")
    res.update({"source": {"ceiling": True, "task": a.task, "arm": arm, "frames": frames, "split": "val",
                           "variant": "ceiling", "cells": ds.map_meta["frozen"]}, "seconds": time.time() - t0,
                "fork_commit": _commit()})
    _write(Path(a.out) / f"ceiling_{a.task}_{arm}", res, cms, pred)


def cmd_head_predict(a) -> None:
    import torch
    from eo.data import seg_dataset as SD
    from eo.data.seg_head_dataset import SegHeadDataset
    from eo.eval import seg_routes as R
    from eo.finetune.seg_head import build_head_model, predict_views
    dev = "cuda" if torch.cuda.is_available() else "cpu"
    if dev == "cuda" and a.expect_gpu and a.expect_gpu not in torch.cuda.get_device_name(0):
        raise SystemExit(f"expected {a.expect_gpu}, CUDA returned {torch.cuda.get_device_name(0)}")
    model, cfg = build_head_model(a.config, a.checkpoint, device=dev, overrides=list(a.override))
    model.float()                                        # fp32 weights; bf16 runs under autocast, as training did
    autocast = {"fp32": None, "bf16": torch.bfloat16}[a.precision]
    spec = SD.spec_from_cfg(cfg, "eval")
    spec.variant = a.variant
    ds = SegHeadDataset(spec, seed=int(cfg.get("seed", 42)))
    views = ds.views.view.values if a.limit is None else ds.views.view.values[: a.limit]
    out = predict_views(model, ds, views, a.variant, a.batch, dev, autocast=autocast, log_every=10)
    rec = {"config": a.config, "checkpoint": a.checkpoint, "overrides": list(a.override), "task": spec.task,
           "frames": spec.frames, "split": spec.split, "variant": a.variant, "precision": a.precision,
           "views": [int(v) for v in views], "seconds": out["seconds"], "route": "C",
           "gpu": torch.cuda.get_device_name(0) if dev == "cuda" else "cpu", "fork_commit": _commit()}
    d = Path(a.out)
    d.mkdir(parents=True, exist_ok=True)
    np.save(d / "pred.npy", out["pred"])
    (d / "record.json").write_text(json.dumps(rec, indent=1, default=str) + "\n")
    print(f"wrote {d}: {len(views)} views -> {len(out['pred'])} samples, {out['seconds']:.0f} s", flush=True)
    res, cms, pred = R.score_pred(spec.task, out["pred"], _views(ds, views))
    res.update({"source": rec, "fork_commit": _commit()})
    _write(d, res, cms, pred)


def cmd_score_head(a) -> None:
    from eo.data import seg_dataset as SD
    from eo.eval import seg_routes as R
    for d in map(Path, a.dirs):
        rec = json.loads((d / "record.json").read_text())
        if rec["split"] != "val":
            raise PermissionError(f"{d}: split {rec['split']}")
        ds = SD.SegDataset(SD.SegSpec(rec["task"], "aligned", rec["frames"], rec["split"]))
        res, cms, pred = R.score_pred(rec["task"], np.load(d / "pred.npy"), _views(ds, rec["views"]))
        res.update({"source": rec, "fork_commit": _commit(), "rescored": True})
        out = d / "rescore"
        _write(out, res, cms, pred)


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("score-cells")
    s.add_argument("--dirs", nargs="+", required=True)
    s.add_argument("--device", default="cpu", choices=("cpu", "cuda"))
    c = sub.add_parser("ceiling-cells")
    c.add_argument("--task", required=True, choices=("pastis", "cloudsen12"))
    c.add_argument("--out", required=True)
    h = sub.add_parser("head-predict")
    h.add_argument("--config", required=True)
    h.add_argument("--checkpoint", required=True)
    h.add_argument("--override", action="append", default=[])
    h.add_argument("--variant", default="full", choices=("full", "wrong"))
    h.add_argument("--precision", default="bf16", choices=("bf16", "fp32"))
    h.add_argument("--batch", type=int, default=64)
    h.add_argument("--limit", type=int, default=None)
    h.add_argument("--expect-gpu", default=None)
    h.add_argument("--out", required=True)
    r = sub.add_parser("score-head")
    r.add_argument("--dirs", nargs="+", required=True)
    a = ap.parse_args()
    {"score-cells": cmd_score_cells, "ceiling-cells": cmd_ceiling_cells, "head-predict": cmd_head_predict,
     "score-head": cmd_score_head}[a.cmd](a)


if __name__ == "__main__":
    main()
